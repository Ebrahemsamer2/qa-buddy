// QA Buddy — report builder.
// Pure string functions (no DOM), so the popup uses them now and the
// background worker can reuse them for Jira in step 6 (importScripts).
(function (global) {
  const esc = (s) =>
    String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

  const clip = (s, n) => (s && s.length > n ? s.slice(0, n - 1) + "…" : s || "");
  const timeOf = (ms) => new Date(ms).toLocaleTimeString([], { hour12: false });

  function path(url) {
    try { const u = new URL(url); return u.pathname + u.search; } catch { return url || ""; }
  }

  const KIND_LABEL = { cancelled: "Cancelled", timeout: "Timeout", slow: "Slow" };
  const netLabel = (n) => KIND_LABEL[n.kind] || n.status || "ERR";
  const TYPE_LABEL = { console: "Console error", error: "Crash", promise: "Unhandled promise rejection" };

  function location(e) {
    if (e.source) return `${e.source}:${e.line}${e.column ? ":" + e.column : ""}`;
    return "";
  }

  // ---------- title suggestion ----------
  function suggestTitle(events, env) {
    const net = events.find((e) => e.type === "network");
    const err = events.find((e) => e.type !== "network");
    if (net) {
      const what = net.kind && net.kind !== "failed" ? net.statusText : net.status || "Network error";
      return clip(`${what} on ${net.method || "GET"} ${path(net.url).split("?")[0]}`, 100);
    }
    if (err) return clip(err.message, 100);
    return clip(env?.title ? `Bug on ${env.title}` : "Bug report", 100);
  }

  // ---------- report object ----------
  // mainId: the event the tester marked as the cause. It leads the report and
  // drives the suggested title; the other events follow as related context.
  function build({ title, description, events, env, screenshot, recordingSince, lastAction, mainId, steps }) {
    const main = events.find((e) => e.id && e.id === mainId) || null;
    const rest = main ? events.filter((e) => e !== main) : events;
    return {
      main,
      steps: steps?.length ? steps : null, // [{ label, time }] recorded by QA Buddy
      lastAction: lastAction || null,
      title: (title || "").trim() || suggestTitle(main ? [main, ...rest] : events, env),
      description: (description || "").trim(),
      createdAt: new Date().toISOString(),
      recordingSince,
      env: env || {},
      screenshot: screenshot || null,
      errors: rest.filter((e) => e.type !== "network"),
      requests: rest.filter((e) => e.type === "network"),
    };
  }

  // ---------- plain text (copy, Jira description) ----------
  function toText(r) {
    const lines = [];
    const add = (...l) => lines.push(...l);

    add(r.title, "");
    if (r.description) add("What happened:", r.description, "");

    add(`Page: ${r.env.title || ""}`, `URL: ${r.env.url || ""}`);
    if (r.lastAction) add(`Last action: ${r.lastAction.label} at ${timeOf(r.lastAction.time)}`);
    add("");

    if (r.steps) {
      add("Steps to reproduce (recorded):");
      r.steps.forEach((s, i) => add(`  ${i + 1}. ${s.label}`));
      add("");
    }


    const errorLines = (e) => [
      `  [${TYPE_LABEL[e.type] || e.type}] ${e.message}${e.count > 1 ? `  (×${e.count})` : ""}`,
      ...(location(e) ? [`    at ${location(e)}`] : []),
      ...(e.frame ? [`    in embedded frame: ${e.frame}`] : []),
      ...(e.stack ? e.stack.split("\n").slice(1, 4).map((s) => "    " + s.trim()) : []),
    ];
    const requestLines = (n) => [
      `  ${n.method || "GET"} ${n.url} → ${n.kind && n.kind !== "failed" ? "" : n.status || "ERR"} ${n.statusText || ""}${n.count > 1 ? `  (×${n.count})` : ""}`.trimEnd(),
      ...(n.frame ? [`    in embedded frame: ${n.frame}`] : []),
      ...(n.requestBody ? [`    Request body: ${clip(n.requestBody, 300)}`] : []),
      ...(n.responseBody ? [`    Response: ${clip(n.responseBody.replace(/\s+/g, " "), 300)}`] : []),
    ];
    const other = r.main ? "Other " : "";

    if (r.main) {
      add("Main problem:", ...(r.main.type === "network" ? requestLines(r.main) : errorLines(r.main)), "");
    }
    if (r.errors.length) {
      add(`${other}${other ? "errors" : "Errors"} (${r.errors.length}):`);
      r.errors.forEach((e) => add(...errorLines(e)));
      add("");
    }
    if (r.requests.length) {
      add(`${other}${other ? "request problems" : "Request problems"} (${r.requests.length}):`);
      r.requests.forEach((n) => add(...requestLines(n)));
      add("");
    }

    add("Environment:",
      `  Browser: ${r.env.browser || ""}`,
      `  OS: ${r.env.os || ""}`,
      `  Screen: ${r.env.screen || ""}  Window: ${r.env.viewport || ""}`,
      `  Language: ${r.env.language || ""}  Time zone: ${r.env.timezone || ""}`,
      `  Reported: ${new Date(r.createdAt).toLocaleString()}`,
      "", "Generated by QA Buddy");
    return lines.join("\n");
  }

  // ---------- standalone HTML file ----------
  function toHtml(r) {
    const errorItem = (e, cls = "") => `
      <article class="item ${cls}">
        <header><span class="tag">${esc(TYPE_LABEL[e.type] || e.type)}</span>${e.count > 1 ? `<span class="repeat">×${e.count}</span>` : ""}<time>${esc(timeOf(e.lastTime || e.time))}</time></header>
        <p class="msg">${esc(e.message)}</p>
        ${location(e) ? `<p class="where">${esc(location(e))}</p>` : ""}
        ${e.frame ? `<p class="where">In embedded frame: ${esc(e.frame)}</p>` : ""}
        ${e.stack ? `<details${cls ? " open" : ""}><summary>Stack trace</summary><pre>${esc(e.stack)}</pre></details>` : ""}
      </article>`;
    const errorItems = r.errors.map((e) => errorItem(e)).join("");

    const requestItem = (n, cls = "") => `
      <article class="item ${cls}">
        <header><span class="tag net">${esc(netLabel(n))} ${esc(n.method || "GET")}</span>${n.count > 1 ? `<span class="repeat">×${n.count}</span>` : ""}<time>${esc(timeOf(n.lastTime || n.time))}</time></header>
        <p class="msg">${esc(n.url)}</p>
        <p class="where">${esc([n.statusText, n.duration != null ? `${n.duration} ms` : "", n.source].filter(Boolean).join(", "))}</p>
        ${n.frame ? `<p class="where">In embedded frame: ${esc(n.frame)}</p>` : ""}
        ${n.requestBody ? `<details><summary>Request body</summary><pre>${esc(n.requestBody)}</pre></details>` : ""}
        ${n.responseBody ? `<details${cls ? " open" : ""}><summary>Response</summary><pre>${esc(n.responseBody)}</pre></details>` : ""}
      </article>`;
    const requestItems = r.requests.map((n) => requestItem(n)).join("");
    const mainItem = r.main ? (r.main.type === "network" ? requestItem(r.main, "main") : errorItem(r.main, "main")) : "";
    const allErrors = r.errors.length + (r.main && r.main.type !== "network" ? 1 : 0);
    const allRequests = r.requests.length + (r.main && r.main.type === "network" ? 1 : 0);

    const envRows = [
      ["Page", r.env.title], ["URL", r.env.url], ["Browser", r.env.browser], ["Operating system", r.env.os],
      ["Screen", r.env.screen], ["Window", r.env.viewport], ["Language", r.env.language],
      ["Time zone", r.env.timezone], ["Recording since", r.recordingSince ? new Date(r.recordingSince).toLocaleString() : ""],
      ["Reported", new Date(r.createdAt).toLocaleString()], ["User agent", r.env.userAgent],
    ].map(([k, v]) => `<tr><th>${esc(k)}</th><td>${esc(v || "—")}</td></tr>`).join("");


    return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(r.title)}</title>
<style>
  :root { --paper:#f6f8f7; --surface:#fff; --ink:#16302b; --muted:#5b6e69; --line:#d5dedb; --marker:#f4c542; --bug:#c8413a; color-scheme: light; }
  @media (prefers-color-scheme: dark) { :root { --paper:#13201d; --surface:#1a2a26; --ink:#e6eeeb; --muted:#93a6a0; --line:#2a3b37; --bug:#e8675f; color-scheme: dark; } }
  * { box-sizing: border-box; }
  body { margin: 0; background: var(--paper); color: var(--ink); font: 15px/1.55 "Segoe UI Variable Text", "SF Pro Text", system-ui, sans-serif; }
  main { max-width: 860px; margin: 0 auto; padding: 40px 24px 64px; }
  h1 { font-size: 26px; line-height: 1.25; margin: 0 0 6px; }
  .meta { color: var(--muted); margin: 0 0 28px; }
  h2 { font-size: 17px; margin: 36px 0 12px; padding-bottom: 6px; border-bottom: 3px solid var(--marker); display: inline-block; }
  .desc { white-space: pre-wrap; background: var(--surface); border: 1px solid var(--line); border-radius: 8px; padding: 14px 16px; margin: 0; }
  .shot img { display: block; width: 100%; border: 1px solid var(--line); border-radius: 8px; }
  .summary { display: flex; gap: 12px; flex-wrap: wrap; margin: 0; padding: 0; list-style: none; }
  .summary li { background: var(--surface); border: 1px solid var(--line); border-radius: 8px; padding: 10px 14px; min-width: 140px; }
  .summary strong { display: block; font-size: 24px; }
  .summary span { color: var(--muted); font-size: 13px; }
  .item { background: var(--surface); border: 1px solid var(--line); border-left: 4px solid var(--bug); border-radius: 8px; padding: 12px 14px; margin-bottom: 10px; }
  .item.main { border: 2px solid var(--bug); border-left-width: 6px; }
  .item header { display: flex; gap: 8px; align-items: center; margin-bottom: 4px; }
  .tag { font-size: 12px; font-weight: 700; padding: 1px 7px; border-radius: 4px; background: var(--bug); color: #fff; }
  .tag.net { background: var(--ink); color: var(--paper); }
  .repeat { font-weight: 700; color: var(--muted); font-size: 13px; }
  time { margin-left: auto; color: var(--muted); font-size: 13px; font-variant-numeric: tabular-nums; }
  .msg { margin: 0; font-weight: 600; word-break: break-word; }
  .where { margin: 2px 0 0; color: var(--muted); font-size: 13px; word-break: break-all; }
  details { margin-top: 8px; }
  summary { cursor: pointer; color: var(--muted); font-size: 13px; }
  pre { margin: 6px 0 0; padding: 10px; background: var(--paper); border-radius: 6px; overflow-x: auto; font: 12.5px/1.5 ui-monospace, "SF Mono", Consolas, monospace; white-space: pre-wrap; word-break: break-all; }
  table { width: 100%; border-collapse: collapse; background: var(--surface); border: 1px solid var(--line); border-radius: 8px; overflow: hidden; }
  th, td { text-align: left; padding: 8px 12px; border-bottom: 1px solid var(--line); vertical-align: top; font-size: 14px; }
  th { width: 170px; color: var(--muted); font-weight: 600; }
  td { word-break: break-word; }
  tr:last-child th, tr:last-child td { border-bottom: 0; }
  .none { color: var(--muted); }
  .steps { background: var(--surface); border: 1px solid var(--line); border-radius: 8px; padding: 12px 16px 12px 40px; margin: 0; }
  .steps li { padding: 3px 0; }
  .steps time { margin-left: 8px; font-size: 12px; }
  td.result { color: var(--muted); width: 40%; }
  tr.bad td.result { color: var(--bug); font-weight: 600; }
  footer { margin-top: 48px; color: var(--muted); font-size: 13px; }
  @media print { details { display: block; } details > * { display: block; } body { background: #fff; } }
</style>
</head>
<body>
<main>
  <h1>${esc(r.title)}</h1>
  <p class="meta">${esc(r.env.url || "")}<br>${r.lastAction ? `Last action: ${esc(r.lastAction.label)} at ${esc(timeOf(r.lastAction.time))}<br>` : ""}Reported ${esc(new Date(r.createdAt).toLocaleString())}</p>

  <ul class="summary">
    <li><strong>${allErrors}</strong><span>Errors</span></li>
    <li><strong>${allRequests}</strong><span>Request problems</span></li>
  </ul>

  ${r.description ? `<h2>What happened</h2><p class="desc">${esc(r.description)}</p>` : ""}

  ${r.steps ? `<h2>Steps to reproduce</h2><ol class="steps">${r.steps.map((s) => `<li>${esc(s.label)} <time>${esc(timeOf(s.time))}</time></li>`).join("")}</ol>` : ""}

  ${r.screenshot ? `<h2>Screenshot</h2><figure class="shot" style="margin:0"><img src="${r.screenshot}" alt="Screenshot of the page when the bug was reported"></figure>` : ""}


  ${mainItem ? `<h2>Main problem</h2>${mainItem}` : ""}

  ${r.main
    ? `${errorItems ? `<h2>Other errors</h2>${errorItems}` : ""}${requestItems ? `<h2>Other request problems</h2>${requestItems}` : ""}`
    : `<h2>Errors</h2>${errorItems || `<p class="none">No errors captured.</p>`}
  <h2>Request problems</h2>${requestItems || `<p class="none">No request problems captured.</p>`}`}

  <h2>Environment</h2>
  <table>${envRows}</table>

  <footer>Generated by QA Buddy. Passwords, tokens and similar values are masked as ***.</footer>
</main>
</body>
</html>`;
  }

  // ---------- Jira description (wiki markup, API v2) ----------
  // Escape characters Jira would treat as formatting; technical text goes in {noformat} blocks.
  const jesc = (s) => String(s ?? "").replace(/([{}\[\]|*_+^~?#\\-])/g, "\\$1").replace(/\r?\n/g, " ");
  const block = (s) => `{noformat}\n${String(s ?? "").replace(/\{noformat\}/g, "")}\n{noformat}`;

  const listJoin = (items) => items.length > 1 ? `${items.slice(0, -1).join(", ")} and ${items[items.length - 1]}` : items.join("");

  // attached: what's attached to the issue, for the closing line
  function toJira(r, attached = { screenshot: true, html: true }) {
    const out = [];
    const add = (...l) => out.push(...l);

    if (r.description) add("h3. What happened", block(r.description), "");

    add(`*Page:* ${jesc(r.env.title || "")}`, `*URL:* ${r.env.url || ""}`);
    if (r.lastAction) add(`*Last action:* ${jesc(r.lastAction.label)} at ${timeOf(r.lastAction.time)}`);
    add("");

    if (r.steps) {
      add("h3. Steps to reproduce", ...r.steps.map((s) => `# ${jesc(s.label)}`), "");
    }


    const errorWiki = (e) => {
      add(`*${jesc(TYPE_LABEL[e.type] || e.type)}*${e.count > 1 ? ` (×${e.count})` : ""}: ${jesc(e.message)}`);
      const where = [location(e) && `at ${location(e)}`, e.frame && `in embedded frame: ${e.frame}`].filter(Boolean).join("\n");
      if (e.stack || where) add(block([where, e.stack].filter(Boolean).join("\n")));
    };
    const requestWiki = (n) => {
      add(`*${jesc(netLabel(n))} ${jesc(n.method || "GET")}*${n.count > 1 ? ` (×${n.count})` : ""} ${jesc(n.statusText || "")}`);
      const details = [
        `URL: ${n.url}`,
        n.duration != null && `Duration: ${n.duration} ms`,
        n.frame && `In embedded frame: ${n.frame}`,
        n.requestBody && `Request body: ${clip(n.requestBody, 1500)}`,
        n.responseBody && `Response: ${clip(n.responseBody, 1500)}`,
      ].filter(Boolean).join("\n");
      add(block(details));
    };

    if (r.main) {
      add("h3. Main problem");
      r.main.type === "network" ? requestWiki(r.main) : errorWiki(r.main);
      add("");
      if (r.errors.length) { add(`h3. Other errors (${r.errors.length})`); r.errors.forEach(errorWiki); add(""); }
      if (r.requests.length) { add(`h3. Other request problems (${r.requests.length})`); r.requests.forEach(requestWiki); add(""); }
    } else {
      add(`h3. Errors (${r.errors.length})`);
      if (!r.errors.length) add("No errors captured.");
      r.errors.forEach(errorWiki);
      add("");
      add(`h3. Request problems (${r.requests.length})`);
      if (!r.requests.length) add("No request problems captured.");
      r.requests.forEach(requestWiki);
      add("");
    }

    add("h3. Environment", "||Item||Value||",
      ...[
        ["Browser", r.env.browser], ["Operating system", r.env.os], ["Screen", r.env.screen],
        ["Window", r.env.viewport], ["Language", r.env.language], ["Time zone", r.env.timezone],
        ["Reported", new Date(r.createdAt).toLocaleString()],
      ].map(([k, v]) => `|${k}|${jesc(v || "") || " "}|`),
      "",
      `_${listJoin([attached.screenshot && "screenshot", attached.html && "full HTML report", attached.replay && "session replay"].filter(Boolean)).replace(/^./, (c) => c.toUpperCase()) || "Nothing"} attached. Generated by QA Buddy; passwords and tokens are masked as \\*\\*\\*._`);
    return out.join("\n");
  }

  function fileName(r) {
    const d = new Date(r.createdAt);
    const pad = (n) => String(n).padStart(2, "0");
    const stamp = `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}-${pad(d.getHours())}${pad(d.getMinutes())}`;
    const slug = r.title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 40) || "bug";
    return `qa-report-${stamp}-${slug}.html`;
  }

  global.QAReport = { suggestTitle, build, toText, toHtml, toJira, fileName };
})(typeof self !== "undefined" ? self : window);
